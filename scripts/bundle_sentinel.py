#!/usr/bin/env python3
"""Merge the six modular Sentinel policies into one policy for HCP Terraform Free.

Why: HCP Terraform Free allows one policy set of up to five policies, and only
one of them may be soft- or hard-mandatory. Deploying six separate policies
would leave all but one as warnings. This script keeps the six readable,
separately tested files as the source of truth and generates
sentinel/hcp/atul_guardrails.sentinel, which is pasted into HCP as one
hard-mandatory policy.

How: imports and params are hoisted to the top (deduplicated), each policy's
"main" rule is renamed "<policy>_main", and a final "main" requires all six.
Every top-level name in a policy carries its own prefix (sov_, sc_, ...), so
the merged file has no name clashes.

Usage:
    python3 scripts/bundle_sentinel.py          # write the bundle
    python3 scripts/bundle_sentinel.py --check  # exit 1 if the bundle is stale (CI)
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SENTINEL_DIR = ROOT / "sentinel"
OUTPUT = SENTINEL_DIR / "hcp" / "atul_guardrails.sentinel"
POLICIES = ["sovereignty", "supply_chain", "encryption", "metadata", "network", "instance_type"]


def build() -> str:
    imports: list[str] = []
    params: list[str] = []
    sections: list[str] = []

    for name in POLICIES:
        text = (SENTINEL_DIR / f"{name}.sentinel").read_text()
        body: list[str] = []
        for line in text.splitlines():
            if line.startswith("import "):
                if line not in imports:
                    imports.append(line)
            elif line.startswith("param "):
                params.append(line)
            else:
                body.append(line)
        section, count = re.subn(r"^main = rule", f"{name}_main = rule", "\n".join(body), flags=re.M)
        if count != 1:
            sys.exit(f"{name}.sentinel: expected exactly one line starting 'main = rule', found {count}")
        sections.append(f"# {'=' * 70}\n# {name}.sentinel\n# {'=' * 70}\n{section.strip()}\n")

    header = (
        "# GENERATED by scripts/bundle_sentinel.py from the six policies in sentinel/.\n"
        "# Do not edit by hand: edit the source policy, then re-run the script.\n"
        "# Deployed to HCP Terraform Free as ONE hard-mandatory policy, because the\n"
        "# Free tier allows only one mandatory policy per organisation.\n"
    )
    final_main = "main = rule {\n\t" + " and\n\t".join(f"{n}_main" for n in POLICIES) + "\n}\n"
    return "\n".join([header, "\n".join(imports), "", "\n".join(params), "", "\n".join(sections), final_main])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed bundle is out of date")
    args = parser.parse_args()

    bundle = build()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != bundle:
            sys.exit("sentinel/hcp/atul_guardrails.sentinel is stale: run python3 scripts/bundle_sentinel.py")
        print("Bundle is up to date.")
        return

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(bundle)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
